var isoAliases = map[string]string{
	"UK": "GB",
}

func matchTextCountry(s string) (Country, bool) {
	raw := strings.TrimSpace(s)
	if raw == "" {
		return UnknownCountry, false
	}
	upper := strings.ToUpper(raw)
	if mapped, ok := isoAliases[upper]; ok {
		upper = mapped
	}
	if c, ok := countries[upper]; ok && c.Code != "ZZ" {
		return c, true
	}
	for _, r := range regionKeywords {
		if strings.Contains(raw, r.key) {
			return CountryByCode(r.code), true
		}
	}
	// 匹配独立前缀 ISO 代码（如 "HK-1", "US_West", "JP2"）
	if len(upper) >= 2 && upper[0] >= 'A' && upper[0] <= 'Z' && upper[1] >= 'A' && upper[1] <= 'Z' {
		if len(upper) == 2 || !(upper[2] >= 'A' && upper[2] <= 'Z') {
			code := upper[:2]
			if mapped, ok := isoAliases[code]; ok {
				code = mapped
			}
			if c, ok := countries[code]; ok && c.Code != "ZZ" {
				return c, true
			}
		}
	}
	return UnknownCountry, false
}

// ServerCountry 按「地区字段 > 服务器名称 > 服务器 IP」顺序识别服务器所在国家。
func ServerCountry(region, name, ip string) Country {
	if c, ok := matchTextCountry(region); ok {
		return c
	}
	if c, ok := matchTextCountry(name); ok {
		return c
	}
	return LookupIP(ip)
}

