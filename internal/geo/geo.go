var sortedIPv4Ranges []ipRange

func init() {
	sortedIPv4Ranges = make([]ipRange, 0, len(builtinCIDRs))
	for _, item := range builtinCIDRs {
		pfx, err := netip.ParsePrefix(item.cidr)
		if err != nil || !pfx.Addr().Is4() {
			continue
		}
		pfx = pfx.Masked()
		b := pfx.Addr().As4()
		start := uint32(b[0])<<24 | uint32(b[1])<<16 | uint32(b[2])<<8 | uint32(b[3])
		bits := pfx.Bits()
		var mask uint32
		if bits > 0 {
			mask = ^uint32(0) << (32 - bits)
		}
		end := start | ^mask
		sortedIPv4Ranges = append(sortedIPv4Ranges, ipRange{
			start:     start,
			end:       end,
			prefixLen: bits,
			code:      item.code,
		})
	}
	// 最长前缀优先匹配
	slices.SortFunc(sortedIPv4Ranges, func(a, b ipRange) int {
		if c := cmp.Compare(b.prefixLen, a.prefixLen); c != 0 {
			return c
		}
		return cmp.Compare(a.start, b.start)
	})
}

func isNonPublic(addr netip.Addr) bool {
	return !addr.IsValid() || addr.IsPrivate() || addr.IsLoopback() || addr.IsLinkLocalUnicast() || addr.IsLinkLocalMulticast() || addr.IsMulticast() || addr.IsUnspecified()
}

// LookupIP 按公网 IP 前缀估算大致国家；私网、无效地址或未命中返回 UnknownCountry。
func LookupIP(raw string) Country {
	s := strings.TrimSpace(raw)
	if s == "" {
		return UnknownCountry
	}
	// 兼容带端口的 host:port
	if ap, err := netip.ParseAddrPort(s); err == nil {
		s = ap.Addr().String()
	}
	addr, err := netip.ParseAddr(s)
	if err != nil {
		return UnknownCountry
	}
	addr = addr.Unmap()
	if isNonPublic(addr) {
		return UnknownCountry
	}
	if addr.Is4() {
		b := addr.As4()
		v := uint32(b[0])<<24 | uint32(b[1])<<16 | uint32(b[2])<<8 | uint32(b[3])
		for _, r := range sortedIPv4Ranges {
			if v >= r.start && v <= r.end {
				return CountryByCode(r.code)
			}
		}
		return UnknownCountry
	}
	// IPv6 按常见运营商/RIR 前缀粗分
	b := addr.As16()
	first16 := uint16(b[0])<<8 | uint16(b[1])
	switch {
	case first16 >= 0x2408 && first16 <= 0x240f: // 中国大陆三大运营商常见 IPv6
		return CountryByCode("CN")
	case first16 == 0x2400 || first16 == 0x2404 || first16 == 0x2406:
		return CountryByCode("SG")
	case first16 == 0x2401 || first16 == 0x2405:
		return CountryByCode("JP")
	case first16 >= 0x2600 && first16 <= 0x26ff:
		return CountryByCode("US")
	case first16 >= 0x2a00 && first16 <= 0x2aff:
		return CountryByCode("DE")
	case first16 >= 0x2800 && first16 <= 0x28ff:
		return CountryByCode("BR")
	case first16 >= 0x2c00 && first16 <= 0x2cff:
		return CountryByCode("ZA")
	}
	return UnknownCountry
}
